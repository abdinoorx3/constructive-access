"""Installed APIs: dependence, apparatus timing, and finite-data energy bounds.

All counts and clock examples are explicitly synthetic. Exact mathematical
checks run before compact outward-rounded rational summaries are serialized.
This tutorial does not establish a physical apparatus's calibration, reset,
stationarity, detector or time-reversal assumptions.
"""
from fractions import Fraction as F
from pathlib import Path
import argparse
import json

from constructive_access.virtual import contrast, sampling, timing


def compact(value):
    """Summarize rationals by deterministic outward bounds at 16 decimals."""
    if isinstance(value, F):
        scale = 10**16
        lower = F((value * scale).numerator // (value * scale).denominator, scale)
        negative = -value * scale
        upper = F(-(negative.numerator // negative.denominator), scale)
        result = {"lower": str(lower), "upper": str(upper)}
        if value and lower == 0:
            result["nonzero_decimal_approximation"] = float(value)
        return result
    if isinstance(value, dict):
        return {key: compact(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [compact(item) for item in value]
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", type=Path, default=Path("results/virtual_tutorial.json")
    )
    args = parser.parse_args()

    # A known uniform Doeblin contract, not observed counts, justifies this
    # conditional reset-bias envelope. Fixed quotas permit predictable routing.
    records = [2000, 2000]
    successes = [1000, 1500]
    alpha = F(1, 20)
    bias = sampling.doeblin_mix_bound(F(1, 2), 10)
    assert bias == F(1, 1024)
    radius = sampling.confidence_radius(records[0], len(records), alpha)
    box_contract = dict(
        records=records,
        successes=successes,
        statistical_radii=radius,
        alpha=alpha,
        conditional_bias_radii=bias,
        calibration_radii=F(1, 1000),
        calibration_failure=F(1, 1000),
    )
    corrected_box = sampling.confidence_box(**box_contract)
    zero_bias_box = sampling.confidence_box(
        **{**box_contract, "conditional_bias_radii": F(0)}
    )
    assert corrected_box["total_failure_upper"] == F(51, 1000)
    for corrected, zero_bias, count, quota in zip(
        corrected_box["intervals"], zero_bias_box["intervals"], successes, records
    ):
        assert corrected[0] <= F(count, quota) <= corrected[1]
        assert corrected[0] == zero_bias[0] - bias
        assert corrected[1] == zero_bias[1] + bias

    # A second externally supplied reset contract uses a known spectral gap.
    spectral_reset = sampling.spectral_mix_bound(F(1, 2), F(1, 4), F(10))
    assert 0 < spectral_reset["conditional_bias_upper"] < F(1, 100)

    # These are exact finite rational clock/exposure controls, not random
    # simulations. Increasing nominal means alone cannot protect inference.
    clocks = timing.make_results()
    for name in ("safe_iid_increment", "safe_random_scale_thermodynamics",
                 "safe_disjoint_symmetric_blocks"):
        assert all(value >= 0 for row in clocks[name]["signed_differences"]
                   for value in row)
    assert clocks["unsafe_random_scale_for_same_dimension"]["hankel_determinant"] > 0
    assert clocks["unsafe_settingwise_ordered_means"]["increase"] > 0
    assert clocks["unsafe_stochastically_ordered_clocks_for_full_cone"]["second_difference"] < 0
    assert clocks["unsafe_overlapping_symmetric_blocks"]["increase"] > 0
    assert clocks["unsafe_antisymmetric_block"]["correlation"] < 0

    # Predeclared curvature contrast -p1+2p2-p3 <= 0 for every reversible
    # spectral mixture. Counts are illustrative stationary-pair records.
    direct_contract = dict(
        lags=[1, 2, 3],
        coefficients=[-1, 2, -1],
        records=[50000, 50000, 50000],
        successes=[35849, 32265, 27572],
        durations=[F(3, 20), F(3, 10), F(9, 20)],
        alpha=alpha,
        conditional_radii=[F(1, 1000)] * 3,
        selection="predeclared",
    )
    direct = contrast.certify_counts(**direct_contract)
    assert contrast.verify(direct, **direct_contract)
    assert direct["support"]["reversible_support_upper"] == 0
    assert direct["entropy_production_rate_lower"] > 0

    # If the same record law is generated by valid disjoint symmetric detector
    # blocks, its full path spans two block lengths plus the intervening gap.
    # A rate statement must charge that exposure even at unchanged counts.
    block_length = F(1, 4)
    full_contract = {
        **direct_contract,
        "durations": [gap + 2 * block_length
                      for gap in direct_contract["durations"]],
    }
    full = contrast.certify_counts(**full_contract)
    assert contrast.verify(full, **full_contract)
    assert full["contrast_lower"] == direct["contrast_lower"]
    assert full["record_kl_lower"] == direct["record_kl_lower"]
    assert 0 < full["entropy_production_rate_lower"] < direct["entropy_production_rate_lower"]

    # The same accounting can be checked for a fixed mathematical lag mixture.
    weights = direct["resource_mixture_weights"]
    endpoint_rate = timing.stationary_rate_bound(
        direct["record_kl_lower"], weights, direct_contract["durations"]
    )
    block_rate = timing.stationary_rate_bound(
        direct["record_kl_lower"], weights, direct_contract["durations"], block_length
    )
    assert block_rate["mean_full_duration"] == endpoint_rate["mean_full_duration"] + 2 * block_length
    assert 0 < block_rate["stationary_entropy_rate_lower"] < endpoint_rate["stationary_entropy_rate_lower"]

    # These are rounded feasible proposals, not certified integer optima.
    equal_record_allocation = contrast.allocation([-1, 2, -1], [1, 1, 1], 150000)
    exposure_allocation = contrast.allocation(
        [-1, 2, -1], full_contract["durations"], 120000
    )
    for allocation in (equal_record_allocation, exposure_allocation):
        assert allocation["actual_cost"] <= allocation["budget"]
        assert allocation["integer_optimality_claimed"] is False

    output = {
        "evidence": "Exact mathematical examples and synthetic counts; no laboratory measurements",
        "dependent_record_box": {
            "assumed_doeblin_minorization": F(1, 2),
            "blind_mixing_blocks": 10,
            "conditional_bias_upper": bias,
            "corrected_confidence_box": corrected_box,
            "known_spectral_gap_example": spectral_reset,
            "note": "Counts do not verify the external mixing or calibration contracts.",
        },
        "exact_clock_and_exposure_controls": clocks,
        "synthetic_predeclared_contrast": {
            "endpoint_certificate": direct,
            "block_length": block_length,
            "full_duration_certificate": full,
            "fixed_mixture_endpoint_rate": endpoint_rate,
            "fixed_mixture_full_duration_rate": block_rate,
            "equal_record_allocation_proposal": equal_record_allocation,
            "full_exposure_allocation_proposal": exposure_allocation,
            "rate_units": "natural entropy per declared model time",
        },
        "limitations": [
            "Dependence coverage requires uniform conditional-mean bounds and fixed quotas.",
            "Contrasts and apparatus envelopes must be frozen before the test records.",
            "Common random clock scaling can preserve the equilibrium moment cone while increasing apparent dimension.",
            "Symmetric disjoint-block and physical time-reversal assumptions must be justified separately.",
            "These illustrative parameters are not hardware calibrations or empirical physical validation.",
        ],
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(compact(output), sort_keys=True, indent=2) + "\n")
    print(json.dumps({
        "status": "tutorial_passed",
        "direct_entropy_bound_positive": True,
        "full_duration_penalty_checked": True,
        "dependent_bias_allowance_checked": True,
    }, sort_keys=True))


if __name__ == "__main__":
    main()
