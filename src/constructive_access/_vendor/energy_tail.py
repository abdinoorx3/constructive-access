#!/usr/bin/env python3
"""Exact certificates for a calibrated counting-channel energy envelope.

The theorem is standard exponential-martingale/Chernoff reasoning. The physical
input is a separately justified channel hazard bound, not sensor-law accuracy.
No measured energy or experimental data are generated by this script.
"""
from __future__ import annotations

from fractions import Fraction as F
from math import ceil
from pathlib import Path
import json
import mpmath as mp


def rational(value):
    if isinstance(value, bool) or not isinstance(value, (int, F, str)):
        raise TypeError("Use an exact integer, Fraction, or rational string")
    return F(value)


def log_bounds(value, terms=96):
    """Positive-series rational enclosure of log(value) for rational value>=1."""
    x = rational(value)
    if type(terms) is not int or x < 1 or terms < 1:
        raise ValueError("Require value>=1 and terms>=1")
    power = 0
    while x >= 2:
        x /= 2
        power += 1

    def unit_interval(y):
        z = (y - 1) / (y + 1)
        low = 2 * sum((z ** (2*k+1) / (2*k+1) for k in range(terms)), F(0))
        remainder = 2 * z ** (2*terms+1) / ((2*terms+1)*(1-z*z))
        return low, low+remainder

    low, high = unit_interval(x)
    l2, u2 = unit_interval(F(2))
    return low + power*l2, high + power*u2


def exponent_lower(mean_upper, threshold):
    mu = rational(mean_upper)
    if type(threshold) is not int:
        raise TypeError("The count threshold must be an integer")
    n = threshold
    if mu <= 0 or n <= mu:
        raise ValueError("Require positive compensator cap and n>mu")
    low, _ = log_bounds(F(n)/mu)
    return n*low-n+mu


def count_cap(mean_upper, failure_probability=F(1,100)):
    """Return n with P(N>=n)<=beta under the stated counting-process contract.

    The returned cap N<=n is conservative by one count. It is not claimed
    to be an exact quantile or a deterministic pathwise cap.
    """
    mu, beta = rational(mean_upper), rational(failure_probability)
    if mu < 0 or not 0 < beta < 1:
        raise ValueError("Require mu>=0 and 0<beta<1")
    if mu == 0:
        return {"count_cap": 0, "mu": "0", "beta": str(beta),
                "proof": "Zero compensator implies zero count almost surely."}
    _, target = log_bounds(1/beta)
    base = ceil(mu)
    width = 1
    while exponent_lower(mu, base+width) < target:
        width *= 2
    low, high = base, base+width
    while high-low > 1:
        middle = (low+high)//2
        if middle > mu and exponent_lower(mu, middle) >= target:
            high = middle
        else:
            low = middle
    certified = exponent_lower(mu, high)
    assert certified >= target
    return {"count_cap": high, "mu": str(mu), "beta": str(beta),
            "chernoff_exponent_lower": str(certified), "log_inverse_beta_upper": str(target),
            "proof": "n*lower(log(n/mu))-n+mu >= upper(log(1/beta))"}


def verify_count_cap(certificate):
    """Recompute the rational inequality from the contract and count cap."""
    try:
        mu, beta = rational(certificate["mu"]), rational(certificate["beta"])
        n = certificate["count_cap"]
        if type(n) is not int or n < 0 or mu < 0 or not 0 < beta < 1:
            return False
        if mu == 0:
            return n == 0
        return n > mu and exponent_lower(mu, n) >= log_bounds(1/beta)[1]
    except (ValueError, KeyError, ZeroDivisionError, TypeError):
        return False


def declared_energy_cap(count_certificate, work_per_event_upper, apparatus_upper):
    """Combine externally supplied nonnegative physical upper bounds.

    Inputs must cover gross supplied energy in a consistent physical unit.
    Native-channel net free energy and total apparatus energy are different.
    """
    w, apparatus = rational(work_per_event_upper), rational(apparatus_upper)
    if not verify_count_cap(count_certificate) or min(w, apparatus) < 0:
        raise ValueError("Invalid count certificate or physical bounds")
    return count_certificate["count_cap"]*w+apparatus


def plain_decimal(value):
    value = F(value)
    return mp.nstr(mp.mpf(value.numerator)/value.denominator, 22)


def main():
    mp.mp.dps = 75
    examples = []
    for mu, beta in [(F(1,10),F(1,100)), (F(10),F(1,100)),
                     (F(100),F(1,1000)), (F(0),F(1,100))]:
        cert = count_cap(mu,beta)
        assert verify_count_cap(cert)
        if mu:
            n = cert["count_cap"]
            x = mp.mpf(mu.numerator)/mu.denominator
            actual_tail = mp.gammainc(n,0,x,regularized=True)
            analytic_bound = mp.exp(-n*mp.log(n/x)+n-x)
            assert actual_tail <= analytic_bound <= mp.mpf(beta.numerator)/beta.denominator
            bad = dict(cert, count_cap=ceil(mu))
            assert not verify_count_cap(bad)
            cert["supplementary_poisson_tail"] = mp.nstr(actual_tail,22)
        examples.append(cert)
    # Uniform parameter-box acquisition example from the previous release.
    # This covers acquisition exposure only: preparation/gaps must be added
    # to the intensity integral in a complete implementation.
    records, duration = 127995,F(3,5)
    gamma_upper, force_upper = F(11,10),F(7,10)
    consuming_rate_upper = gamma_upper*(1+force_upper)
    exposure = records*duration
    physical = count_cap(consuming_rate_upper*exposure,F(1,100))
    work_upper = log_bounds((1+force_upper)/(1-force_upper))[1]
    native_cap = declared_energy_cap(physical,work_upper,0)
    # An arbitrary apparatus allowance is not silently presented as measured.
    illustrative_apparatus_per_record = F(1,2)
    illustrative_total = declared_energy_cap(physical,work_upper,
                                             records*illustrative_apparatus_per_record)
    assert illustrative_total-native_cap == records*illustrative_apparatus_per_record
    invalid_input_checks = 0
    for function, args in [(count_cap,(0.1,)), (count_cap,(True,)),
                           (log_bounds,(F(2),1.5)), (exponent_lower,(F(1),2.5)),
                           (declared_energy_cap,(physical,0.1,F(0)))]:
        try:
            function(*args)
        except (TypeError,ValueError):
            invalid_input_checks += 1
        else:
            raise AssertionError("Inexact/invalid physical input was accepted")
    physical.update({"records":records,"acquisition_exposure":str(exposure),
        "consuming_event_rate_upper":str(consuming_rate_upper),
        "gross_work_per_event_upper_in_kBT":plain_decimal(work_upper),
        "acquisition_native_gross_energy_cap_in_kBT":plain_decimal(native_cap),
        "illustrative_apparatus_per_record_in_kBT":str(illustrative_apparatus_per_record),
        "illustrative_combined_cap_in_kBT":plain_decimal(illustrative_total),
        "apparatus_status":"Hypothetical declared allowance for arithmetic demonstration; unmeasured, not a physical estimate.",
        "scope":"At least99% probability under independently calibrated consuming-channel hazard and work bounds. Native acquisition only until preparation, gaps, reset and apparatus bounds are supplied."})
    upgraded_exposures=[]
    for larger_count in [133852,140399]:
        larger_exposure=larger_count*duration
        larger_cert=count_cap(consuming_rate_upper*larger_exposure,F(1,100))
        assert verify_count_cap(larger_cert)
        upgraded_exposures.append({"records":larger_count,
            "acquisition_exposure":str(larger_exposure),"count_certificate":larger_cert,
            "native_gross_energy_cap_in_kBT":plain_decimal(declared_energy_cap(larger_cert,work_upper,0)),
            "scope":"Recomputed exposure for upgraded statistical design; same separate channel contract and apparatus exclusions."})
    result={"status":"passed","theory":"Established counting-process exponential supermartingale and Chernoff bound, exact rational certificate.",
            "contract":["Calibrated predictable event intensity with stopped compensator<=mu", "Gross supplied energy per counted event<=declared work bound", "Every uncounted apparatus contribution separately bounded", "Any probability of calibration-contract failure accounted for separately"],
            "examples":examples,"triangle_acquisition":physical,
            "upgraded_acquisition_exposures":upgraded_exposures,
            "invalid_input_checks":invalid_input_checks,
            "combined_guarantee":"Wrong committed inference probability<=alpha and over-budget probability<=beta imply joint failure<=alpha+beta, plus independently justified contract failure probability.",
            "empirical_data":False,"versions":{"mpmath":mp.__version__},"randomness":"none"}
    root=Path(__file__).resolve().parents[1]
    (root/'results/energy_tail.json').write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps({"status":"passed","count_cap":physical['count_cap'],
                      "native_gross_energy_cap_in_kBT":plain_decimal(native_cap),
                      "overrun_probability_at_most":"1/100","apparatus_calibrated":False},indent=2))


if __name__=='__main__':
    main()
